// Builds supabase/seed.sql from supabase/words/*.json. Run: node scripts/build-seed.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = new URL("../supabase/words/", import.meta.url).pathname;
const out = new URL("../supabase/seed.sql", import.meta.url).pathname;

const seen = new Set();
const words = [];
for (const file of readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
  for (const w of JSON.parse(readFileSync(join(dir, file), "utf8"))) {
    const key = w.spanish_word.trim().toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    words.push(w);
  }
}

const lit = (v) => (v == null ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const rows = words.map(
  (w) =>
    `  (${lit(w.spanish_word.trim())}, ${lit(w.category)}, ${Number(w.level)}, ${lit(w.english)}, ${lit(w.example_sentence)}, ${lit(w.grammar_note)}, ${lit(w.description)})`,
);

writeFileSync(
  out,
  `-- Generated by scripts/build-seed.mjs (${words.length} words)\n` +
    "insert into como.words (spanish_word, category, level, english, example_sentence, grammar_note, description) values\n" +
    rows.join(",\n") +
    "\non conflict (spanish_word) do nothing;\n",
);

const byLevel = [1, 2, 3].map((l) => words.filter((w) => w.level === l).length);
console.log(`${words.length} words → ${out} (levels 1/2/3: ${byLevel.join("/")})`);
